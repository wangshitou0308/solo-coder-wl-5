func (h *AlertHandler) MatchGap(c *gin.Context) {
	idStr := c.Param("id")
	id, err := uuid.Parse(idStr)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "无效的预警ID"})
		return
	}

	radius, _ := strconv.ParseFloat(c.DefaultQuery("radius", "5"), 64)

	results, err := h.alertService.MatchGap(id, radius)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

	c.JSON(http.StatusOK, gin.H{"data": results})
}
